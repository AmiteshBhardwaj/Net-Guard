  function drawChart() {
    state.chartFrame = 0;
    const progress = state.chartTransitionAt && !reduceMotion
      ? Math.min(1, (performance.now() - state.chartTransitionAt) / 220) : 1;
    const canvases = [$("#traffic-chart"), $("#threat-chart"), $("#ingress-chart")]
      .filter(canvas => canvas && canvas.getBoundingClientRect().width > 0);
    if (!canvases.length) return;
    for (const canvas of canvases) {
      const rect = canvas.getBoundingClientRect();
      if (!rect.width || !rect.height) continue;
      const dpr = Math.min(window.devicePixelRatio || 1, 2);
      const width = Math.round(rect.width * dpr);
      const height = Math.round(rect.height * dpr);
      if (canvas.width !== width || canvas.height !== height) {
        canvas.width = width;
        canvas.height = height;
      }
      const ctx = canvas.getContext("2d");
      ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
      const w = rect.width, h = rect.height;
      ctx.clearRect(0, 0, w, h);
      ctx.strokeStyle = "rgba(126,164,182,.15)";
      ctx.lineWidth = 1;
      ctx.setLineDash([3, 5]);
      for (let row = 0; row < 4; row++) {
        const y = 4 + row * (h - 8) / 3;
        ctx.beginPath(); ctx.moveTo(0, y); ctx.lineTo(w, y); ctx.stroke();
      }
      ctx.setLineDash([]);
      const max = Math.max(10, ...state.series);
      const step = w / (state.series.length - 1);
      const slide = progress < 1 ? (1 - progress) * step : 0;
      const points = state.series.map((value, i) => ({
        x: i * step + slide,
        y: h - 5 - value / max * (h - 16)
      }));
      const gradient = ctx.createLinearGradient(0, 0, 0, h);
      gradient.addColorStop(0, "rgba(85,215,229,.18)");
      gradient.addColorStop(1, "rgba(85,215,229,0)");
      ctx.beginPath();
      points.forEach((point, i) => i ? ctx.lineTo(point.x, point.y) : ctx.moveTo(point.x, point.y));
      ctx.lineTo(w, h); ctx.lineTo(0, h); ctx.closePath();
      ctx.fillStyle = gradient; ctx.fill();
      ctx.lineWidth = 2;
      points.forEach((point, i) => {
        if (!i) return;
        const previous = points[i - 1];
        const before = points[Math.max(0, i - 2)];
        const after = points[Math.min(points.length - 1, i + 1)];
        ctx.beginPath();
        ctx.moveTo(previous.x, previous.y);
        ctx.bezierCurveTo(
          previous.x + (point.x - before.x) / 6,
          previous.y + (point.y - before.y) / 6,
          point.x - (after.x - previous.x) / 6,
          point.y - (after.y - previous.y) / 6,
          point.x, point.y
        );
        ctx.strokeStyle = state.markers[i] ? "#ff5f68" : "#55d7e5";
        ctx.stroke();
      });
      state.markers.forEach((marked, i) => {
        if (!marked || !points[i]) return;
        ctx.beginPath(); ctx.arc(points[i].x, points[i].y, 3, 0, Math.PI * 2);
        ctx.fillStyle = "#ff5f68"; ctx.fill();
      });
      const last = points.at(-1);
      ctx.beginPath(); ctx.arc(last.x, last.y, 3, 0, Math.PI * 2);
      ctx.fillStyle = "#d5fcff"; ctx.shadowColor = "#55d7e5"; ctx.shadowBlur = 10; ctx.fill(); ctx.shadowBlur = 0;
    }
    if (progress < 1) state.chartFrame = requestAnimationFrame(drawChart);
    else state.chartTransitionAt = 0;
    state.chartDirty = false;
  }

  function scheduleChart(slide = false) {
    if (slide) state.chartTransitionAt = performance.now();
    state.chartDirty = true;
    if (!state.chartFrame) state.chartFrame = requestAnimationFrame(() => {
      state.chartFrame = 0;
      drawChart();
    });
  }

  function pushPoint(value, isAlert = false) {
    state.series.push(Math.max(0, Number(value) || 0));
    state.series.shift();
    state.markers.push(isAlert);
    state.markers.shift();
    scheduleChart(true);
    if (isAlert) showChartPin();
  }

  function showChartPin() {
    const pins = [$("#chart-pin"), $("#ingress-chart-pin")].filter(Boolean);
    const label = attackInfo[state.activeAttack]?.label || state.incident?.label || "Anomaly";
    const technique = attackInfo[state.activeAttack]?.technique || "T1046";
    pins.forEach(pin => {
      pin.textContent = `${label} detected · ${technique}`;
      pin.classList.remove("visible");
      void pin.offsetWidth;
      pin.classList.add("visible");
      const wrap = pin.closest(".chart-wrap");
      const ripple = document.createElement("span");
      ripple.className = "chart-shockwave";
      ripple.style.left = `${Math.max(45, wrap.clientWidth * .78)}px`;
      ripple.style.top = `${Math.max(20, wrap.clientHeight * .35)}px`;
      wrap.append(ripple);
      setTimeout(() => ripple.remove(), 800);
    });
  }

